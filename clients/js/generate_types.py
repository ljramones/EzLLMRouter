"""Generate TypeScript payload types from the client contract resources."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
SOURCES = {
    "Wire02": ROOT
    / "tests/fixtures/contracts/wp-a-03-c01/EZLLMROUTER-WP-A-SCHEMAS-v0.3-CORRECTION-01.json",
    "Wire03": HERE / "dev12_schemas.json",
    "IntegrationV1": HERE / "integration_schema.json",
    "IntegrationV2": HERE / "integration_schema_v2.json",
    "IntegrationV3": HERE / "integration_schema_v3.json",
}


def literal(value):
    if isinstance(value, dict):
        return "{ " + "; ".join(json.dumps(k) + ": " + literal(v) for k, v in value.items()) + " }"
    if isinstance(value, list):
        return "[" + ", ".join(literal(v) for v in value) + "]"
    return json.dumps(value, ensure_ascii=True)


def shape_type(shape):
    if "$ref" in shape:
        return shape["$ref"].rsplit("/", 1)[1]
    if "const" in shape:
        return literal(shape["const"])
    if "enum" in shape:
        return " | ".join(literal(value) for value in shape["enum"])
    if "oneOf" in shape or "anyOf" in shape:
        return " | ".join(
            "(" + shape_type(part) + ")" for part in shape.get("oneOf", shape.get("anyOf"))
        )
    kind = shape.get("type")
    if kind == "object" or "properties" in shape:
        required = set(shape.get("required", []))
        fields = [
            json.dumps(key) + ("" if key in required else "?") + ": " + shape_type(value)
            for key, value in shape.get("properties", {}).items()
        ]
        extra = shape.get("additionalProperties", True)
        if extra is not False:
            # Arbitrary fields remain unknown until application code narrows them.
            fields.append("[key: string]: unknown")
        return "{ " + "; ".join(fields) + " }"
    if kind == "array":
        return "Array<" + shape_type(shape.get("items", {})) + ">"
    return {
        "integer": "number",
        "number": "number",
        "string": "string",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


def generate():
    lines = [
        "// Generated by generate_types.py. Do not edit by hand.",
        "// Shapes are static types; runtime and semantic validation remain authoritative.",
        "",
    ]
    for namespace, source in SOURCES.items():
        lines.append("export declare namespace " + namespace + " {")
        for name, shape in json.loads(source.read_text())["$defs"].items():
            lines.append("  export type " + name + " = " + shape_type(shape) + ";")
        lines.extend(["}", ""])
    return "\n".join(lines)


if __name__ == "__main__":
    (HERE / "contracts.d.cts").write_text(generate())
