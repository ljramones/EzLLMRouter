"""Checked handler capabilities; component views follow the existing route guards."""

from __future__ import annotations
from collections.abc import Iterable, Mapping, Sequence
from email.message import Message
from typing import TYPE_CHECKING, Protocol, TypedDict
from urllib.parse import SplitResult
from ..records import Record
from .application import OperatorSession

if TYPE_CHECKING:
    from .application import OperatorApplication
    from ..registry import Registry
    from ..user_management import UserManager
    from ..local_connectors import LocalConnectors
    from ..personal_campaign import PersonalCampaign
    from ..integration_credentials import DatabaseCredentialStore
    from ..operator_demo import ProviderValidationRunner
    from ..store import SQLiteStore

Session = tuple[str, OperatorSession]


class SessionDetails(TypedDict, total=False):
    csrf: str
    principal_id: str
    role: str
    named_login: bool
    username: str | None
    display_name: str | None
    user_auth_version: int | None
    must_change_password: bool
    wire_token: str | None
    expires: float


class Writer(Protocol):
    def write(self, data: bytes, /) -> int: ...


class OperatorContext(Protocol):
    @property
    def application(self) -> OperatorApplication: ...
    @property
    def headers(self) -> Message[str, str]: ...
    @property
    def path(self) -> str: ...
    @property
    def client_address(self) -> tuple[str, int] | str: ...
    @property
    def wfile(self) -> Writer: ...
    @property
    def _registry(self) -> Registry: ...
    @property
    def _accounts(self) -> UserManager: ...
    @property
    def _connectors(self) -> LocalConnectors: ...
    @property
    def _campaign(self) -> PersonalCampaign: ...
    @property
    def _credentials(self) -> DatabaseCredentialStore: ...
    @property
    def _validation(self) -> ProviderValidationRunner: ...
    @property
    def _successor_store(self) -> SQLiteStore: ...

    close_connection: bool

    def send_response(self, code: int, message: str | None = None) -> None: ...
    def send_header(self, keyword: str, value: str) -> None: ...
    def end_headers(self) -> None: ...
    def read_body(self, length: int) -> bytes: ...
    def _send(
        self,
        status: int,
        payload: object,
        *,
        content_type: str = "application/json; charset=utf-8",
        extra: Iterable[tuple[str, str]] = (),
    ) -> None: ...
    def _fail(self, status: int, code: str) -> None: ...
    def _send_csv(
        self, filename: str, columns: Sequence[str], rows: Iterable[Mapping[str, object]]
    ) -> None: ...
    def _session_cookie(self, token: str, max_age: int) -> str: ...
    def _body_limit(self) -> int: ...
    def _make_session_room(
        self, item: OperatorSession, discarded: list[OperatorSession]
    ) -> bool: ...
    def _session_details(self, item: OperatorSession) -> SessionDetails | None: ...
    def _session_payload(self, item: OperatorSession) -> Record: ...
    def _revoke_session_tokens(self, items: Iterable[OperatorSession]) -> None: ...
    def _login(self, body: Record, outcome: dict[str, bool]) -> None: ...
    def _login_rejected(self, outcome: dict[str, bool], status: int, code: str) -> None: ...
    def _user_write(self, body: Record, session: Session, *, delete: bool = False) -> None: ...
    def _local_connector_write(
        self, body: Record, session: Session, *, delete: bool = False
    ) -> None: ...
    def get_registry_inventory(
        self, path: SplitResult, session: Session, body: None, scope: str | None
    ) -> None: ...
