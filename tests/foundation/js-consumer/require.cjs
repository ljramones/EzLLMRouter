"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const pkg = require("@cognitivedynamics/ezllmrouter-client");
const resolved = fs.realpathSync(require.resolve("@cognitivedynamics/ezllmrouter-client"));
const allowed = fs.realpathSync(path.join(__dirname, "node_modules")) + path.sep;
assert.ok(resolved.startsWith(allowed), `unexpected import path: ${resolved}`);
assert.equal(typeof pkg.EzLLMRouterClient, "function");
console.log(JSON.stringify({ version: JSON.parse(fs.readFileSync(path.join(path.dirname(resolved), "package.json"), "utf8")).version, resolved, allowed, node: process.execPath }));
